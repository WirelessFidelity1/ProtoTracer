"""Pack selected Animated textures for the 51x32 uncovered HUB75 area.

Run with Python 3; original full-resolution assets remain unchanged.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'lib/ProtoTracer/Assets/Textures/Animated'
OUT = ASSETS / 'Utils/MoviesData.h'
WIDTH, HEIGHT = 51, 32
MOVIES = ('PS2', 'Rick', 'Gamecube', 'VaporWave')


def pack(data):
    result = bytearray()
    i = 0
    while i < len(data):
        run = 1
        while i + run < len(data) and data[i + run] == data[i] and run < 128:
            run += 1
        if run >= 3:
            result.extend((127 + run, data[i]))
            i += run
        else:
            start = i
            i += 1
            while i < len(data) and i - start < 128:
                if i + 2 < len(data) and data[i] == data[i+1] == data[i+2]:
                    break
                i += 1
            result.append(i - start - 1)
            result.extend(data[start:i])
    return result


def array(name, values, kind='uint8_t'):
    return f'static const {kind} {name}[] PROGMEM = {{\n' + ''.join(
        ','.join(map(str, values[i:i+32])) + ',\n' for i in range(0, len(values), 32)
    ) + '};\n'


def unpack(data):
    result = bytearray()
    i = 0
    while i < len(data):
        token = data[i]
        i += 1
        if token < 128:
            count = token + 1
            result.extend(data[i:i+count])
            i += count
        else:
            result.extend([data[i]] * (token - 127))
            i += 1
    return bytes(result)



def build():
    output = ['// Generated by tools/build_movies.py. Do not edit.\n#pragma once\n#include <Arduino.h>\n',
              'namespace MoviesData {\nstruct Clip { const char* name; const uint8_t* data; const uint32_t* offsets; const uint8_t* palette; uint16_t frames; };\n']
    clips = []
    total = 0
    for key in MOVIES:
        path = ASSETS / (key + '.h')
        text = path.read_text()
        width, height = map(int, re.search(r'Image\(frame0000, rgbColors, (\d+), (\d+)', text).groups())
        frames = {name: bytes(map(int, re.findall(r'\d+', body))) for name, body in
                  re.findall(r'::(frame\d+)\[\] PROGMEM = \{([^}]*)\}', text)}
        order = re.search(r'::sequence\[\] = \{([^}]*)\}', text).group(1).split(',')
        palette = list(map(int, re.findall(r'\d+', re.search(r'::rgbColors\[\] PROGMEM = \{([^}]*)\}', text).group(1))))
        packed = bytearray()
        offsets = []
        for name in order:
            frame = frames[name.strip()]
            assert len(frame) == width * height, (path, name, len(frame))
            sampled = bytes(frame[min(height-1, int((y+.5)*height/HEIGHT))*width + min(width-1, int((x+.5)*width/WIDTH))]
                            for y in range(HEIGHT) for x in range(WIDTH))
            offsets.append(len(packed))
            encoded = pack(sampled)
            assert unpack(encoded) == sampled, (path, name, 'compression round trip')
            assert max(sampled) * 3 + 2 < len(palette), (path, name, 'palette index')
            packed.extend(encoded)
        key = path.stem
        output.extend((array(key+'Data', packed), array(key+'Offsets', offsets, 'uint32_t'), array(key+'Palette', palette)))
        clips.append(f'{{"{key.upper()}", {key}Data, {key}Offsets, {key}Palette, {len(order)}}}')
        total += len(packed)
    output.append('static const Clip clips[] = {\n' + ',\n'.join(clips) + '\n};\n}\n')
    OUT.write_text(''.join(output))
    print(f'{len(clips)} clips, {total:,} packed frame bytes')


if __name__ == '__main__':
    build()
