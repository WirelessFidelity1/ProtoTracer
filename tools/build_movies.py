"""Pack selected Animated textures for the 51x32 uncovered HUB75 area.

Run with Python 3; original full-resolution assets remain unchanged.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'lib/ProtoTracer/Assets/Textures/Animated'
OUT = ASSETS / 'Utils/MoviesData.h'
WIDTH, HEIGHT = 51, 32
MOVIES = ('Rick', 'Gamecube', 'VaporWave')
GIF_MOVIES = {'Boyksr': ROOT / 'boyksr.gif'}
GIF_MOVIES.update({
    'Gif' + re.sub(r'[^A-Za-z0-9]', '', path.stem): path
    for path in sorted((ROOT / 'gifs').glob('*'), key=lambda path: path.name.lower())
    if path.suffix.lower() == '.gif' and path.stem.lower() != 'jork'
})


def gif_frames(path, invert=False):
    """Composite GIF frames, preserve aspect ratio, and sample at playback's 42 ms tick."""
    from PIL import Image, ImageOps
    from bisect import bisect_right
    from math import ceil

    frames, ends = [], []
    duration = 0
    with Image.open(path) as gif:
        for index in range(gif.n_frames):
            gif.seek(index)
            frame = ImageOps.contain(gif.convert('RGBA'), (WIDTH, HEIGHT), Image.Resampling.LANCZOS)
            if invert:
                alpha = frame.getchannel('A')
                frame = ImageOps.invert(frame.convert('RGB')).convert('RGBA')
                frame.putalpha(alpha)
            canvas = Image.new('RGBA', (WIDTH, HEIGHT), (0, 0, 0, 255))
            canvas.alpha_composite(frame, ((WIDTH-frame.width)//2, (HEIGHT-frame.height)//2))
            frames.append(canvas.convert('RGB'))
            duration += max(10, gif.info.get('duration', 100))
            ends.append(duration)
    atlas = Image.new('RGB', (WIDTH, HEIGHT*len(frames)))
    for index, frame in enumerate(frames):
        atlas.paste(frame, (0, index*HEIGHT))
    indexed = atlas.quantize(colors=256, dither=Image.Dither.NONE)
    palette = indexed.getpalette()
    samples = []
    for tick in range(ceil(duration/42)):
        index = bisect_right(ends, tick*42)
        samples.append(indexed.crop((0, index*HEIGHT, WIDTH, (index+1)*HEIGHT)).tobytes())
    print(f'{path.name}: {len(frames)} GIF frames, {duration} ms -> {len(samples)} playback frames')
    return samples, palette


def pack(data):
    result = bytearray()
    i = 0
    while i < len(data):
        run = 1
        while i + run < len(data) and data[i + run] == data[i] and run < 128:
            run += 1
        if run >= 3:
            result.extend((127 + run, data[i]))
            i += run
        else:
            start = i
            i += 1
            while i < len(data) and i - start < 128:
                if i + 2 < len(data) and data[i] == data[i+1] == data[i+2]:
                    break
                i += 1
            result.append(i - start - 1)
            result.extend(data[start:i])
    return result


def array(name, values, kind='uint8_t'):
    return f'static const {kind} {name}[] PROGMEM = {{\n' + ''.join(
        ','.join(map(str, values[i:i+32])) + ',\n' for i in range(0, len(values), 32)
    ) + '};\n'


def unpack(data):
    result = bytearray()
    i = 0
    while i < len(data):
        token = data[i]
        i += 1
        if token < 128:
            count = token + 1
            result.extend(data[i:i+count])
            i += count
        else:
            result.extend([data[i]] * (token - 127))
            i += 1
    return bytes(result)



def build():
    output = ['// Generated by tools/build_movies.py. Do not edit.\n#pragma once\n#include <Arduino.h>\n',
              'namespace MoviesData {\nstruct Clip { const char* name; const uint8_t* data; const uint32_t* offsets; const uint8_t* palette; uint16_t frames; };\n']
    clips = []
    total = 0
    for key in MOVIES:
        path = ASSETS / (key + '.h')
        text = path.read_text()
        width, height = map(int, re.search(r'Image\(frame0000, rgbColors, (\d+), (\d+)', text).groups())
        frames = {name: bytes(map(int, re.findall(r'\d+', body))) for name, body in
                  re.findall(r'::(frame\d+)\[\] PROGMEM = \{([^}]*)\}', text)}
        order = re.search(r'::sequence\[\] = \{([^}]*)\}', text).group(1).split(',')
        palette = list(map(int, re.findall(r'\d+', re.search(r'::rgbColors\[\] PROGMEM = \{([^}]*)\}', text).group(1))))
        packed = bytearray()
        offsets = []
        for name in order:
            frame = frames[name.strip()]
            assert len(frame) == width * height, (path, name, len(frame))
            sampled = bytes(frame[min(height-1, int((y+.5)*height/HEIGHT))*width + min(width-1, int((x+.5)*width/WIDTH))]
                            for y in range(HEIGHT) for x in range(WIDTH))
            offsets.append(len(packed))
            encoded = pack(sampled)
            assert unpack(encoded) == sampled, (path, name, 'compression round trip')
            assert max(sampled) * 3 + 2 < len(palette), (path, name, 'palette index')
            packed.extend(encoded)
        key = path.stem
        output.extend((array(key+'Data', packed), array(key+'Offsets', offsets, 'uint32_t'), array(key+'Palette', palette)))
        clips.append(f'{{"{key.upper()}", {key}Data, {key}Offsets, {key}Palette, {len(order)}}}')
        total += len(packed)
    for key, path in GIF_MOVIES.items():
        samples, palette = gif_frames(path)
        packed, offsets = bytearray(), []
        for frame in samples:
            assert len(frame) == WIDTH*HEIGHT
            assert max(frame)*3+2 < len(palette)
            encoded = pack(frame)
            assert unpack(encoded) == frame, (path, 'compression round trip')
            offsets.append(len(packed))
            packed.extend(encoded)
        output.extend((array(key+'Data', packed), array(key+'Offsets', offsets, 'uint32_t'), array(key+'Palette', palette)))
        label = path.stem.upper().replace('\\', '\\\\').replace('"', '\\"')
        clips.append(f'{{"{label}", {key}Data, {key}Offsets, {key}Palette, {len(samples)}}}')
        total += len(packed)
    output.append('static const Clip clips[] = {\n' + ',\n'.join(clips) + '\n};\n}\n')
    OUT.write_text(''.join(output))
    print(f'{len(clips)} clips, {total:,} packed frame bytes')


if __name__ == '__main__':
    build()
